#!/usr/bin/env python3
"""Generate the reference pages in kb/reference/ from the inventory (skills/blender/inventory/) and the 4.5 manual's
index (docs.py's cache, for links). Everything in them was read from Blender 4.5.14 itself.

  python3 tools/gen_reference.py

Pages: nodes-shader.md, nodes-geometry.md, nodes-compositor.md, nodes-texture.md (every node, every socket),
modifiers.md, constraints.md, settings.md (render, Cycles, EEVEE, output, colour management, units, light, camera,
world: the registered default and what a fresh file starts with), operators.md (every operator, one line each),
python.md (bmesh.ops, mathutils, bpy_extras), and README.md.
"""
import gzip
import json
import os
import re
from collections import defaultdict

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
INV = os.path.join(ROOT, "skills", "blender", "inventory")
OUT = os.path.join(ROOT, "kb", "reference")
DOCS = os.path.expanduser("~/.cache/agentic-blender/docs-4.5/index.jsonl.gz")
MANUAL = "https://docs.blender.org/manual/en/4.5/"
API = "https://docs.blender.org/api/4.5/"


def jl(name):
    with gzip.open(os.path.join(INV, name), "rt", encoding="utf-8") as f:
        return [json.loads(line) for line in f]


S = {s["id"]: s for s in jl("structs.jsonl.gz")}
NODES = jl("nodes.jsonl.gz")
OPS = jl("operators.jsonl.gz")
MODS = jl("modules.jsonl.gz")
FACTORY = json.load(open(os.path.join(INV, "factory.json")))
META = json.load(open(os.path.join(INV, "meta.json")))
TYPED = json.load(open(os.path.join(INV, "typed.json")))

# manual pages by section and lower-case title (without " Node", " Modifier", " Constraint")
manual = defaultdict(dict)
if os.path.exists(DOCS):
    with gzip.open(DOCS, "rt", encoding="utf-8") as f:
        for line in f:
            p = json.loads(line)
            if p["kind"] != "manual":
                continue
            rel = p["url"].split("/en/4.5/")[1]
            title = p["title"].split(" - Blender")[0].strip().lower()
            for section in ("render/shader_nodes/", "modeling/geometry_nodes/", "compositing/types/",
                            "editors/texture_node/types/", "modeling/modifiers/", "animation/constraints/"):
                if rel.startswith(section):
                    for t in {title, re.sub(r" (node|modifier|constraint)$", "", title)}:
                        manual[section].setdefault(t, p["url"])

SECTION = {"ShaderNodeTree": "render/shader_nodes/", "GeometryNodeTree": "modeling/geometry_nodes/",
           "CompositorNodeTree": "compositing/types/", "TextureNodeTree": "editors/texture_node/types/"}
HEAD = ("Generated by `tools/gen_reference.py` from what Blender {v} reports about itself "
        "(`skills/blender/inventory/`, read by `skills/blender/scripts/inventory.py`). **default** is the value Blender "
        "registers; **new** is what a node, modifier or constraint made from Python actually starts with (≠ where they "
        "differ); **factory** is what a fresh file holds. Look one item up from the command line with "
        "`skills/blender/scripts/kb.py`.\n")


def val(v):
    if isinstance(v, float):
        return f"{v:g}"
    if isinstance(v, list):
        if all(isinstance(x, (int, float)) for x in v):
            return "(" + ", ".join(f"{x:g}" if isinstance(x, float) else str(x) for x in v) + ")"
        return json.dumps(v)
    if v is None:
        return ""
    return str(v)


def esc(t):
    return (t or "").replace("|", "\\|").replace("\n", " ")


def anchor(text):
    return re.sub(r"[^a-z0-9 -]", "", text.lower()).strip().replace(" ", "-")


def prop_row_new(p, new):
    """A row with the value a newly created thing starts with; ≠ where it differs from the registered default."""
    t = p["type"].lower() + (f"[{p['array']}]" if p.get("array") else "") + (f" {p['subtype'].lower()}" if p.get("subtype") else "")
    if p.get("to"):
        t += f" → `{p['to']}`"
    d = "" if p["type"] in ("POINTER", "COLLECTION") else val(p.get("default"))
    nv = val(new.get(p["id"])) if p["id"] in new and p["type"] not in ("POINTER", "COLLECTION") else ""
    if nv.startswith("<"):
        nv = ""
    mark = " ≠" if nv and nv != d else ""
    rng = ""
    if p.get("range") and p["range"] != [None, None]:
        r = p.get("soft") or p["range"]
        rng = f"{val(r[0])} .. {val(r[1])}"
    items = ""
    if p.get("items"):
        ids = [i["id"] for i in p["items"]]
        items = ", ".join(f"`{i}`" for i in ids[:14]) + (f", … ({len(ids)})" if len(ids) > 14 else "")
    flags = " (read-only)" if p.get("readonly") else ""
    return f"| `{p['id']}`{flags} | {esc(t)} | {esc(d)} | {esc(nv)}{mark} | {esc(rng or items)} | {esc(p.get('desc', ''))} |"


def prop_row(p, factory=None):
    t = p["type"].lower()
    if p.get("array"):
        t += f"[{p['array']}]"
    if p.get("subtype"):
        t += f" {p['subtype'].lower()}"
    if p.get("to"):
        t += f" → `{p['to']}`"
    d = "" if p["type"] in ("POINTER", "COLLECTION") else val(p.get("default"))
    rng = ""
    if p.get("range") and p["range"] != [None, None]:
        r = p.get("soft") or p["range"]
        rng = f"{val(r[0])} .. {val(r[1])}"
    items = ""
    if p.get("items"):
        ids = [i["id"] for i in p["items"]]
        items = ", ".join(f"`{i}`" for i in ids[:14]) + (f", … ({len(ids)})" if len(ids) > 14 else "")
    flags = " (read-only)" if p.get("readonly") else ""
    row = f"| `{p['id']}`{flags} | {esc(t)} | {esc(d)} | {esc(rng or items)} | {esc(p.get('desc', ''))} |"
    if factory is not None:
        fv = val(factory.get(p["id"])) if p["id"] in factory else ""
        mark = " ≠" if fv and d and fv != d and p["type"] != "POINTER" else ""
        row = f"| `{p['id']}`{flags} | {esc(t)} | {esc(d)} | {esc(fv)}{mark} | {esc(rng or items)} | {esc(p.get('desc', ''))} |"
    return row


def node_pages():
    kinds = [("nodes-shader.md", "ShaderNodeTree", "Shader nodes"), ("nodes-geometry.md", "GeometryNodeTree", "Geometry nodes"),
             ("nodes-compositor.md", "CompositorNodeTree", "Compositor nodes"), ("nodes-texture.md", "TextureNodeTree", "Texture nodes")]
    counts = {}
    for fname, tree, title in kinds:
        nodes = sorted([n for n in NODES if tree in n.get("trees", [])], key=lambda n: (n.get("label") or n["name"]).lower())
        counts[fname] = len(nodes)
        lines = [f"# {title} in Blender {META['blender']}", "", HEAD.format(v=META["blender"]),
                 f"{len(nodes)} node types can be added to a `{tree}`. Sockets marked *hidden* are off until a node "
                 "setting turns them on (a Math node's third input, a Mix node's typed sockets). Add a node with "
                 "`tree.nodes.new(\"<idname>\")`; reach a socket by name (`node.inputs[\"Base Color\"]`) or, when names "
                 "repeat, by identifier.", "", "## Index", ""]
        lines += [", ".join(f"[{n.get('label') or n['name']}](#{anchor((n.get('label') or n['name']) + ' ' + n['id'])})"
                            for n in nodes), ""]
        for n in nodes:
            label = n.get("label") or n["name"]
            url = manual[SECTION[tree]].get(label.lower())
            lines += [f"## {label} `{n['id']}`", ""]
            meta = [f"[manual]({url})"] if url else []
            others = [t.replace("NodeTree", "").lower() for t in n.get("trees", []) if t != tree]
            if others:
                meta.append("also in: " + ", ".join(others))
            if n.get("desc"):
                meta.append(esc(n["desc"]))
            if meta:
                lines += [" · ".join(meta), ""]
            for side in ("inputs", "outputs"):
                socks = n.get(side, [])
                if not socks:
                    continue
                lines += [f"| {side[:-1]} | identifier | type | default | range |", "|---|---|---|---|---|"]
                for s in socks:
                    name = s["name"] + (" *(hidden)*" if s.get("hidden_by_default") else "")
                    ident = s["id"] if s["id"] != s["name"] else ""
                    rng = f"{val(s['range'][0])} .. {val(s['range'][1])}" if s.get("range") else ""
                    t = s["type"].replace("NodeSocket", "") + (", multi-input" if s.get("multi_input") else "")
                    lines.append(f"| {esc(name)} | {esc(ident)} | {t} | {esc(val(s.get('default')))} | {rng} |")
                lines.append("")
            props = [p for p in n.get("props", []) if p["id"] not in ("rna_type",)]
            if props:
                lines += ["| property | type | default | new | range or values | description |", "|---|---|---|---|---|---|"]
                lines += [prop_row_new(p, n.get("new_values", {})) for p in props] + [""]
        open(os.path.join(OUT, fname), "w").write("\n".join(lines))
    return counts


def chain(s):
    out = []
    while s:
        out.append(s)
        s = S.get(s.get("base"))
    return out


def typed_pages(fname, base, enum_struct, title, section, suffix):
    items = next(p for p in S[enum_struct]["props"] if p["id"] == "type")["items"]
    subs = [s for s in S.values() if s.get("base") == base]
    by_name = {s["name"].lower(): s for s in subs}
    by_id = {s["id"].lower(): s for s in subs}
    lines = [f"# {title} in Blender {META['blender']}", "", HEAD.format(v=META["blender"]),
             f"{len(items)} types. Add one with `obj.{'modifiers' if base == 'Modifier' else 'constraints'}.new(name, "
             f"type)`; the settings below are on the returned `{base}` subtype. Settings shared by every {base.lower()} "
             f"(listed once at the end) are on `{base}`.", "", "## Index", "",
             ", ".join(f"[{i['name']}](#{anchor(i['name'] + ' ' + i['id'])})" for i in items), ""]
    made = TYPED["modifiers" if base == "Modifier" else "constraints"]
    for it in items:
        key = it["name"].lower()
        rec = made.get(it["id"], {})
        s = S.get(rec.get("struct")) if rec.get("struct") else None   # the type Blender really made for this value
        url = manual[section].get(key)
        lines += [f"## {it['name']} `{it['id']}`", ""]
        on = f"on a {rec['object']} object" if rec.get("object") else ""
        meta = ([f"[manual]({url})"] if url and not it["id"].startswith("GREASE_PENCIL") else []) + \
               ([f"type `{s['id']}`"] if s else [f"not created here: {rec.get('error', '?')}"]) + ([on] if on else []) + \
               ([esc(it["desc"])] if it.get("desc") else [])
        if meta:
            lines += [" · ".join(meta), ""]
        if s and s["props"]:
            lines += ["| property | type | default | new | range or values | description |", "|---|---|---|---|---|---|"]
            lines += [prop_row_new(p, rec.get("new_values", {})) for p in s["props"]] + [""]
    lines += [f"## Shared by every {base.lower()} (`{base}`)", "", "| property | type | default | range or values | description |",
              "|---|---|---|---|---|"] + [prop_row(p) for p in S[base]["props"]] + [""]
    open(os.path.join(OUT, fname), "w").write("\n".join(lines))
    return len(items)


def settings_page():
    groups = [
        ("Render settings", "RenderSettings", "scene.render", FACTORY.get("render")),
        ("Cycles", "CyclesRenderSettings", "scene.cycles", FACTORY.get("cycles")),
        ("EEVEE", "SceneEEVEE", "scene.eevee", FACTORY.get("eevee")),
        ("Output image format", "ImageFormatSettings", "scene.render.image_settings", FACTORY.get("image_settings")),
        ("View (colour management)", "ColorManagedViewSettings", "scene.view_settings", FACTORY.get("view_settings")),
        ("Display (colour management)", "ColorManagedDisplaySettings", "scene.display_settings", FACTORY.get("display_settings")),
        ("Units", "UnitSettings", "scene.unit_settings", FACTORY.get("unit_settings")),
        ("Baking", "BakeSettings", "scene.render.bake", FACTORY.get("bake")),
        ("Light (all types)", "Light", "light data", (FACTORY.get("lights") or {}).get("Light")),
        ("Sun light", "SunLight", "light data, type SUN", None),
        ("Point light", "PointLight", "light data, type POINT", None),
        ("Spot light", "SpotLight", "light data, type SPOT", None),
        ("Area light", "AreaLight", "light data, type AREA", None),
        ("Camera", "Camera", "camera data", (FACTORY.get("cameras") or {}).get("Camera")),
        ("Depth of field", "CameraDOFSettings", "camera.dof", None),
        ("World", "World", "scene.world", FACTORY.get("world")),
        ("Cycles light settings", "CyclesLightSettings", "light.cycles", None),
        ("Cycles world settings", "CyclesWorldSettings", "world.cycles", None),
        ("Cycles object settings", "CyclesObjectSettings", "object.cycles", None),
        ("Cycles view layer", "CyclesRenderLayerSettings", "view_layer.cycles", None),
        ("View layer", "ViewLayer", "view_layer", None),
    ]
    lines = [f"# Scene, render, light and camera settings in Blender {META['blender']}", "", HEAD.format(v=META["blender"]),
             "The **factory** column is the value in the factory startup file (Blender's default cube scene), where it "
             "was read; **≠** marks where it differs from the registered default: that is what a fresh file really "
             "starts with. An empty scene from `read_factory_settings(use_empty=True)` has no camera, light or world, "
             "but its scene-level settings are the factory ones.", "", "## Index", "",
             ", ".join(f"[{g[0]}](#{anchor(g[0])})" for g in groups), ""]
    for title, sid, where, fac in groups:
        s = S.get(sid)
        if not s:
            continue
        lines += [f"## {title}", "", f"`{sid}` · `{where}` · [API]({API}bpy.types.{sid}.html)" if not s.get("reachable_only")
                  else f"`{sid}` · `{where}`", ""]
        props = [p for c in chain(s) if c["id"] not in ("ID", "PropertyGroup") for p in c["props"]] if sid.endswith("Light") and sid != "Light" else s["props"]
        if sid.endswith("Light") and sid != "Light":
            props = s["props"]
        if fac:
            lines += ["| property | type | default | factory | range or values | description |", "|---|---|---|---|---|---|"]
            lines += [prop_row(p, fac) for p in props] + [""]
        else:
            lines += ["| property | type | default | range or values | description |", "|---|---|---|---|---|"]
            lines += [prop_row(p) for p in props] + [""]
    open(os.path.join(OUT, "settings.md"), "w").write("\n".join(lines))
    return len(groups)


def operators_page():
    by_ns = defaultdict(list)
    for o in OPS:
        if "error" in o:
            continue
        by_ns[o["id"].split(".")[0]].append(o)
    lines = [f"# Operators in Blender {META['blender']}", "", HEAD.format(v=META["blender"]),
             f"{sum(len(v) for v in by_ns.values())} operators in {len(by_ns)} namespaces, one line each. Many need a "
             "window, an area or a selection that a headless run does not have (`skills/blender/areas/running.md`); "
             "prefer the data API where there is one. Parameters: `kb.py op <name>`. *(py)* marks an operator "
             "written in Python, with its module.", "", "## Namespaces", "",
             ", ".join(f"[{ns}](#{anchor(ns)}) ({len(v)})" for ns, v in sorted(by_ns.items())), ""]
    for ns, ops in sorted(by_ns.items()):
        lines += [f"## {ns}", ""]
        for o in sorted(ops, key=lambda o: o["id"]):
            py = f" *(py: {o['module']})*" if o.get("module") else ""
            n = len(o.get("params", []))
            lines.append(f"- `bpy.ops.{o['id']}` ({n} parameter{'s' if n != 1 else ''}){py}: {esc(o.get('desc') or o.get('name', ''))}")
        lines.append("")
    open(os.path.join(OUT, "operators.md"), "w").write("\n".join(lines))
    return sum(len(v) for v in by_ns.values())


def python_page():
    want = ["bmesh.ops", "bmesh.utils", "bmesh.geometry", "mathutils", "mathutils.geometry", "mathutils.bvhtree",
            "mathutils.kdtree", "mathutils.noise", "mathutils.interpolate", "bpy_extras.object_utils",
            "bpy_extras.view3d_utils", "bpy_extras.mesh_utils", "bpy_extras.image_utils", "bpy_extras.io_utils",
            "bpy_extras.anim_utils", "bpy_extras.node_shader_utils", "bpy.utils", "bpy.path", "bl_math"]
    mods = {m["module"]: m for m in MODS}
    lines = [f"# Python modules around bpy in Blender {META['blender']}", "", HEAD.format(v=META["blender"]),
             "Every public function and class of the modules agents reach for most, with the first lines of its "
             "docstring as Blender ships it. Full docstring: `kb.py py <module.name>`.", "", "## Modules", "",
             ", ".join(f"[{m}](#{anchor(m)})" for m in want if m in mods), ""]
    n = 0
    for name in want:
        m = mods.get(name)
        if not m:
            continue
        lines += [f"## {name}", "", f"[API]({API}{name}.html)", ""]
        for e in m.get("members", []):
            doc = (e.get("doc") or "").strip()
            if name == "bmesh.ops":   # its docstrings carry the full signature and the returned dict
                sig = next((l for l in doc.splitlines() if l.startswith("BMeshOpFunc") or l.startswith(".. function")), "")
                body = [l for l in doc.splitlines() if l.strip() and not l.startswith(("BMeshOpFunc", ".. function", "->", "dict("))]
                ret = next((l for l in doc.splitlines() if l.startswith("->")), "")
                lines.append(f"- **`{e['name']}`** `{sig.replace('BMeshOpFunc ', '')[:300]}` {ret[:160]}")
                if body:
                    lines.append(f"  {esc(' '.join(body)[:300])}")
            else:
                first = " ".join(l.strip() for l in doc.splitlines()[:3] if l.strip() and not l.strip().startswith(":"))
                kind = "class" if e["kind"] == "class" else ""
                sig = e.get("signature", "")
                lines.append(f"- **`{e['name']}`**{(' ' + kind) if kind else ''}{('`' + sig[:160] + '`') if sig else ''}: {esc(first[:280])}")
                if e.get("members") and e["kind"] == "class":
                    lines.append("  members: " + ", ".join(f"`{x['name']}`" for x in e["members"][:60]))
            n += 1
        lines.append("")
    open(os.path.join(OUT, "python.md"), "w").write("\n".join(lines))
    return n


def main():
    os.makedirs(OUT, exist_ok=True)
    counts = node_pages()
    nmod = typed_pages("modifiers.md", "Modifier", "Modifier", "Modifiers", "modeling/modifiers/", "modifier")
    ncon = typed_pages("constraints.md", "Constraint", "Constraint", "Constraints", "animation/constraints/", "constraint")
    nset = settings_page()
    nops = operators_page()
    npy = python_page()
    readme = [f"# Reference: Blender {META['blender']}", "",
              "Generated pages: exact for this version, because they were read from Blender itself, not written from "
              "memory. The hand-written guides are in `skills/blender/areas/`; these pages are what they point into "
              "when a name, a socket, a default or a range is needed. Regenerate after a Blender update with "
              "`skills/blender/scripts/inventory.py` then `tools/gen_reference.py`.", "",
              "| Page | What it lists |", "|---|---|",
              f"| [nodes-shader.md](nodes-shader.md) | {counts['nodes-shader.md']} shader nodes, every socket (name, identifier, type, default, range), their settings, manual links |",
              f"| [nodes-geometry.md](nodes-geometry.md) | {counts['nodes-geometry.md']} geometry and function nodes |",
              f"| [nodes-compositor.md](nodes-compositor.md) | {counts['nodes-compositor.md']} compositor nodes |",
              f"| [nodes-texture.md](nodes-texture.md) | {counts['nodes-texture.md']} texture nodes (the legacy texture node editor) |",
              f"| [modifiers.md](modifiers.md) | {nmod} modifier types with every setting |",
              f"| [constraints.md](constraints.md) | {ncon} constraint types with every setting |",
              f"| [settings.md](settings.md) | {nset} groups of scene, render, Cycles, EEVEE, output, colour, unit, light, camera and world settings, with what a fresh file starts with |",
              f"| [operators.md](operators.md) | {nops} operators by namespace, one line each |",
              f"| [python.md](python.md) | {npy} functions and classes of bmesh, mathutils, bpy_extras, bpy.utils, bpy.path |", ""]
    open(os.path.join(OUT, "README.md"), "w").write("\n".join(readme))
    sizes = {f: os.path.getsize(os.path.join(OUT, f)) // 1024 for f in sorted(os.listdir(OUT))}
    print(json.dumps(dict(nodes=counts, modifiers=nmod, constraints=ncon, operators=nops, python=npy, kb=sizes)))


if __name__ == "__main__":
    main()
